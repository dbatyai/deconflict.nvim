local nav = require("deconflict.nav")

local function mk(...)
  return vim.tbl_map(function(l)
    return { kind = "ours", lnum = l, marker_col = { 0, 7 } }
  end, { ... })
end

describe("nav.next", function()
  local m = mk(3, 7, 10)
  it("finds the next marker strictly after lnum", function()
    eq(7, nav.next(m, 3, false).lnum)
    eq(3, nav.next(m, 1, false).lnum)
    eq(10, nav.next(m, 8, true).lnum)
  end)
  it("handles after-last with and without wrap", function()
    is_nil(nav.next(m, 10, false))
    eq(3, nav.next(m, 12, true).lnum)
  end)
  it("wraps to a single marker on the cursor line", function()
    eq(5, nav.next(mk(5), 5, true).lnum)
    is_nil(nav.next(mk(5), 5, false))
  end)
  it("returns nil for an empty list", function()
    is_nil(nav.next({}, 1, true))
  end)
end)

describe("nav.prev", function()
  local m = mk(3, 7, 10)
  it("finds the previous marker strictly before lnum", function()
    eq(3, nav.prev(m, 7, false).lnum)
    eq(10, nav.prev(m, 20, false).lnum)
  end)
  it("handles before-first with and without wrap", function()
    is_nil(nav.prev(m, 3, false))
    eq(10, nav.prev(m, 1, true).lnum)
  end)
  it("wraps to a single marker on the cursor line", function()
    eq(5, nav.prev(mk(5), 5, true).lnum)
  end)
  it("returns nil for an empty list", function()
    is_nil(nav.prev({}, 1, true))
  end)
end)
